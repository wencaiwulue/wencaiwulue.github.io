#!/usr/bin/env node
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const manifest = JSON.parse(fs.readFileSync(path.join(__dirname, 'url-migration.json'), 'utf-8'));

// Build a map of old paths to new paths
const redirectMap = new Map();
for (const entry of manifest) {
  redirectMap.set(entry.from, entry.to);
}

console.log('Looking for files with internal links...');
const filesToCheck = [
  // Check if there's an index or home page
  // Check sidebars file
];

// Find all markdown files
const docsDir = path.join(__dirname, '..', 'docs');
const allMarkdownFiles = [];

function findMarkdowns(dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      findMarkdowns(fullPath);
    } else if (entry.name.endsWith('.md')) {
      allMarkdownFiles.push(fullPath);
    }
  }
}

findMarkdowns(docsDir);

let updatedFiles = 0;

console.log('\nChecking all markdown files for internal links...');

for (const file of allMarkdownFiles) {
  const content = fs.readFileSync(file, 'utf-8');
  let newContent = content;
  let fileUpdated = false;

  // Look for links like [text](/some/path)
  const linkRegex = /\[([^\]]*)\]\((\/[^)\s]+)/g;
  let match;

  while ((match = linkRegex.exec(content)) !== null) {
    const fullMatch = match[0];
    const linkText = match[1];
    const link = match[2];

    // Remove hash
    const hashIndex = link.indexOf('#');
    const baseLink = hashIndex !== -1 ? link.substring(0, hashIndex) : link;
    const hash = hashIndex !== -1 ? link.substring(hashIndex) : '';

    if (redirectMap.has(baseLink) && redirectMap.get(baseLink) !== baseLink) {
      const newLink = redirectMap.get(baseLink) + hash;
      console.log(`Found in ${path.basename(file)}: ${baseLink} → ${redirectMap.get(baseLink)}`);
      newContent = newContent.split(`(${link})`).join(`(${newLink})`);
      fileUpdated = true;
    }
  }

  if (fileUpdated) {
    console.log(`Updating ${path.basename(file)}...`);
    fs.writeFileSync(file, newContent, 'utf-8');
    updatedFiles++;
  }
}

// Also check docusaurus.config.js? Or sidebars.js? Sidebars.js uses autogenerated, so should be fine.

console.log(`\nUpdated ${updatedFiles} files with new links.`);
